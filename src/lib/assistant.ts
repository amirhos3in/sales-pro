const fallback = [
  "سناریو را دقیق‌تر بگویید: حضوری، تلفن، یا دایرکت؟ و جملهٔ خود مشتری را بنویسید.",
  "برای شروع، یکی از این‌ها را بفرستید: «قیمت بالاست»، «وقت ندارم»، «منشی وصل نمی‌کند»، یا متن دایرکت باز.",
].join(" ");

export function assistantReply(input: string) {
  const text = input.trim();
  if (!text) return "یک جمله از مشتری بنویسید تا پاسخ کوتاه پیشنهاد بدهم.";

  if (/وقت ندارم|فرصت ندارم|الان نه/.test(text)) {
    return [
      "وقت را انکار نکنید؛ کوچکش کنید.",
      "«فقط یک سؤال: پیگیری سرنخ با خود شماست یا تیم؟ اگر با شماست، فردا نه و چهل و پنج برای همان یک سؤال مناسب است؟»",
      "اگر باز هم نماند، ساعت برگشت را همان لحظه ثبت کنید و تماس را کش ندهید.",
    ].join("\n");
  }

  if (/بفرست|بررسی کنم|فکر کنم|کاتالوگ/.test(text)) {
    return [
      "ارسال کلی، بهانه را تمدید می‌کند.",
      "«کدام بخش را باید ببینید، اسکریپت یا هزینه؟ همان یک صفحه را می‌فرستم و پنجشنبه ساعت یازده زنگ می‌زنم. خودتان تصمیم می‌گیرید؟»",
      "اگر شخص دیگری باید ببیند، نامش را قبل از فرستادن بگیرید.",
    ].join("\n");
  }

  if (/قیمت|گران|تخفیف|بودجه/.test(text)) {
    return [
      "قبل از تخفیف، مرجع مقایسه را دربیاورید.",
      "«نسبت به چه چیزی بالا است؟ اگر نسبت به سرنخ‌هایی است که سرد می‌شوند، عدد ماه پیش را همین‌جا حساب کنیم.»",
      "اگر سقف واقعی بود، دامنه را ببرید داخل سقف: یک فاز، نه کل پروژه. امتیاز را مشروط بدهید.",
    ].join("\n");
  }

  if (/منشی|دربان|وصل نمی‌|گیت/.test(text)) {
    return [
      "منشی را دور نزنید. به او یک جملهٔ قابل انتقال بدهید.",
      "«موضوع دربارهٔ تماس‌هایی است که به جلسه نمی‌رسند. مسئول این بخش چه کسی است و چه ساعتی برای تماس کوتاه بهتر است؟»",
      "نام را اگر دارید بگویید. معرفی طولانی شرکت را برای خود تصمیم‌گیر نگه دارید.",
    ].join("\n");
  }

  if (/دایرکت|چت|اینستا|کامنت/.test(text)) {
    return [
      "دایرکت را مثل تماس کوتاه ببندید، نه مثل نامه.",
      "پیام اول ادامهٔ همان کامنت باشد. بعد از فهم مسئله، دو گزینه بدهید: «قالب آماده را بفرستم یا ده دایرکت واقعی‌تان را در پلن پلاس بررسی کنیم؟»",
      "از «نظرتان چیست؟» برای بستن استفاده نکنید.",
    ].join("\n");
  }

  if (/spin|نیاز|درد|مصاحبه/.test(text)) {
    return [
      "چهار لایه را قاطی نکنید. پیشنهاد را بعد از پیامد بگویید.",
      "وضعیت: این کار الان با چه ابزاری انجام می‌شود؟ مسئله: کجا می‌شکند؟ پیامد: اگر بماند این ماه چه هزینه‌ای دارد؟ بازدهی: اگر جمع شود چه عددِ قابل دیدن عوض می‌شود؟",
    ].join("\n");
  }

  if (/زبان بدن|گارد|اعتماد|لحن/.test(text)) {
    return [
      "اگر دست‌ها بسته است و پا به سمت در چرخیده، ارائه را ادامه ندهید.",
      "«اگر جایی از این حرف با شرایط شما نمی‌خواند همان را بگویید.» بعد ساکت بمانید.",
      "تعریف از دفتر را حذف کنید. یک مشاهدهٔ دقیق کافی است.",
    ].join("\n");
  }

  if (/batna|مذاکره|لنگر|بن‌بست|امتیاز|zopa/.test(text)) {
    return [
      "اگر فقط روی یک عدد گیر کرده‌اید، متغیر تازه اضافه کنید نه تخفیف تازه.",
      "«روی این قیمت به توافق نمی‌رسیم. یا فاز اول را جدا می‌کنیم، یا شروع را به ماه بعد می‌بریم. کدام برای مدیرتان قابل دفاع است؟»",
      "هر امتیازی که می‌دهید باید چیزی برگرداند. بعدش سکوت.",
    ].join("\n");
  }

  if (/بستن|کلوز|قرارداد|نشانه/.test(text)) {
    return [
      "اگر دربارهٔ زمان شروع یا پرداخت پرسید، به معرفی برنگردید.",
      "«اگر تأیید کتبی تا پنجشنبه برسد، شروع دوشنبه است. پیش‌نویس را همین امروز بفرستم؟»",
      "همان روز جمع‌بندی کتبی بدهید تا پشیمانی بعد از خرید جا نگیرد.",
    ].join("\n");
  }

  if (/قیف|لندینگ|صفحه|نرخ تبدیل|cac|ltv/.test(text)) {
    return [
      "یک چیز را عوض کنید و همان را بشمارید: بازدید، شروع ثبت‌نام، پرداخت.",
      "هدف صفحهٔ دوره در این آکادمی ۳ تا ۵ درصد است. اگر پایین‌ترید، تبلیغ را زیاد نکنید.",
      "CAC را بر تعداد خریدار همان دوره تقسیم کنید و ببینید ارتقای پلن، این هزینه را در ادامه برمی‌گرداند یا نه.",
    ].join("\n");
  }

  return fallback;
}

export const assistantPrompts = [
  "مشتری گفت قیمت بالاست",
  "گفت وقت ندارم",
  "منشی وصل نمی‌کند",
  "دایرکت را چطور ببندم؟",
  "نشانه‌های آمادگی خرید چیست؟",
];

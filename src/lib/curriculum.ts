export function trackStaticParams() {
  return tracks.map((track) => ({ track: track.slug }));
}

export function moduleStaticParams() {
  return tracks.flatMap((track) =>
    track.modules.map((courseModule) => ({
      track: track.slug,
      module: courseModule.slug,
    })),
  );
}

export function lessonStaticParams() {
  return tracks.flatMap((track) =>
    track.modules.flatMap((courseModule) =>
      courseModule.lessons.map((lesson) => ({
        track: track.slug,
        module: courseModule.slug,
        lesson: lesson.slug,
      })),
    ),
  );
}

export function lessonKey(track: string, moduleSlug: string, lesson: string) {
  return `${track}/${moduleSlug}/${lesson}`;
}

export function findTrack(slug: string) {
  return tracks.find((track) => track.slug === slug);
}

export function findModule(track: Track, slug: string) {
  return track.modules.find((module) => module.slug === slug);
}

export function findLesson(module: Module, slug: string) {
  return module.lessons.find((lesson) => lesson.slug === slug);
}

export function allLessons() {
  return tracks.flatMap((track) =>
    track.modules.flatMap((module) =>
      module.lessons.map((lesson) => ({ track, module, lesson })),
    ),
  );
}

export function trackLessons(track: Track) {
  return track.modules.flatMap((module) =>
    module.lessons.map((lesson) => ({ module, lesson })),
  );
}

export function canAccess(
  item: { preview?: boolean; minPlan: PlanId },
  plan: PlanId | null,
) {
  if (item.preview) return true;
  if (!plan) return false;
  return PLAN_RANK[plan] >= PLAN_RANK[item.minPlan];
}

export function modulePlan(module: Module): PlanId {
  return module.lessons.reduce<PlanId>((current, lesson) => {
    return PLAN_RANK[lesson.minPlan] > PLAN_RANK[current] ? lesson.minPlan : current;
  }, "eco");
}

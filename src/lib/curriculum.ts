import { PLAN_RANK, type PlanId } from "@/lib/plans";

export type Lesson = {
  slug: string;
  title: string;
  minutes: number;
  minPlan: PlanId;
  preview?: boolean;
  lead: string;
  points: string[];
  scriptTitle: string;
  script: string[];
  practice: string;
  quiz?: {
    question: string;
    options: string[];
    answer: number;
  };
};

export type Module = {
  slug: string;
  title: string;
  summary: string;
  lessons: Lesson[];
};

export type TrackIcon = "users" | "handshake" | "phone" | "megaphone";

export type Track = {
  slug: string;
  title: string;
  subtitle: string;
  description: string;
  icon: TrackIcon;
  modules: Module[];
};

type Draft = Omit<Lesson, "minPlan">;

function lesson(
  slug: string,
  title: string,
  minutes: number,
  lead: string,
  points: string[],
  scriptTitle: string,
  script: string[],
  practice: string,
  extra?: Pick<Lesson, "preview" | "quiz">,
): Draft {
  return { slug, title, minutes, lead, points, scriptTitle, script, practice, ...extra };
}

function moduleOf(
  slug: string,
  title: string,
  summary: string,
  minPlan: PlanId,
  lessons: Draft[],
): Module {
  return {
    slug,
    title,
    summary,
    lessons: lessons.map((item) => ({ ...item, minPlan })),
  };
}


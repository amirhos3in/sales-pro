export type LessonRecord = {
  progress: number;
  score?: number;
  passed: boolean;
};

export type PathState = Record<string, LessonRecord>;

export const PATH_KEY = "nexsell-academy-path-v1";

export function emptyPath(): PathState {
  return {};
}

export function accessPlanFromSubscription(
  active: boolean,
  planType: "monthly" | "quarterly" | "yearly" | null | undefined,
): AccessPlan {
  if (!active) return "none";
  if (planType === "monthly") return "eco";
  if (planType === "quarterly") return "plus";
  if (planType === "yearly") return "pro";
  return "none";
}

export function sampleHalfway(): PathState {
  const online = TRACKS[0];
  return {
    [online.lessons[0].id]: { progress: 100, score: 100, passed: true },
    [online.lessons[1].id]: { progress: 45, passed: false },
  };
}

export function readPath(raw: string | null): PathState {
  if (!raw) return {};
  try {
    const parsed = JSON.parse(raw) as unknown;
    if (!parsed || typeof parsed !== "object") return {};
    const out: PathState = {};
    for (const [key, value] of Object.entries(parsed)) {
      if (!value || typeof value !== "object") continue;
      const row = value as Partial<LessonRecord>;
      if (typeof row.progress !== "number" || typeof row.passed !== "boolean") continue;
      out[key] = {
        progress: Math.max(0, Math.min(100, row.progress)),
        passed: row.passed,
        score: typeof row.score === "number" ? row.score : undefined,
      };
    }
    return out;
  } catch {
    return {};
  }
}

export function scoreOf(correct: number, total: number) {
  if (total <= 0) return 0;
  return Math.round((correct / total) * 100);
}

export function passedScore(score: number) {
  return score >= PASS_MARK;
}

export function courseOpen(plan: AccessPlan, track: AcademyTrack) {
  return PLAN_RANK[plan] >= PLAN_RANK[track.required];
}

export function lessonUnlocked(track: AcademyTrack, index: number, state: PathState, plan: AccessPlan) {
  if (!courseOpen(plan, track)) return false;
  if (index === 0) return true;
  return Boolean(state[track.lessons[index - 1].id]?.passed);
}

export type LessonPhase = "plan" | "sequence" | "ready" | "progress" | "passed";

export function lessonPhase(track: AcademyTrack, index: number, state: PathState, plan: AccessPlan): LessonPhase {
  if (!courseOpen(plan, track)) return "plan";
  if (!lessonUnlocked(track, index, state, plan)) return "sequence";
  const row = state[track.lessons[index].id];
  if (row?.passed) return "passed";
  if (row) return "progress";
  return "ready";
}

export function trackProgress(track: AcademyTrack, state: PathState) {
  const done = track.lessons.filter((item) => state[item.id]?.passed).length;
  return { done, total: track.lessons.length, percent: track.lessons.length ? Math.round((done / track.lessons.length) * 100) : 0 };
}

export function overallProgress(state: PathState, plan: AccessPlan) {
  const open = TRACKS.filter((track) => courseOpen(plan, track));
  const total = open.reduce((sum, track) => sum + track.lessons.length, 0);
  const done = open.reduce((sum, track) => sum + track.lessons.filter((item) => state[item.id]?.passed).length, 0);
  return { done, total, percent: total ? Math.round((done / total) * 100) : 0 };
}

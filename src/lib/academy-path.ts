const WRONG = [
  "همان اول قیمت را بگویید تا مشتری معطل نشود.",
  "تخفیف سریع، بدون کشف نیاز، فروش را قطعی می‌کند.",
  "اعتراض یعنی مکالمه تمام شده و نباید پیگیری کرد.",
  "اگر مشتری ساکت شد، یعنی آمادهٔ امضاست.",
];

function quiz(facts: [string, string, string, string]): QuizItem[] {
  const prompts = [
    "کدام جمله با این مرحله جور است؟",
    "کدام اقدام درست است؟",
    "کدام کار را نباید انجام داد؟",
    "نشانهٔ اجرای درست این مرحله چیست؟",
  ];
  return facts.map((fact, index) => {
    const options = [WRONG[index % 4], WRONG[(index + 1) % 4], WRONG[(index + 2) % 4], WRONG[(index + 3) % 4]];
    const slot = index % 4;
    options.splice(slot, 0, fact);
    return { prompt: prompts[index], options: options.slice(0, 4), answer: slot };
  });
}

function lesson(id: string, title: string, minutes: number, summary: string, facts: [string, string, string, string]): AcademyLesson {
  return { id, title, minutes, summary, quiz: quiz(facts) };
}

